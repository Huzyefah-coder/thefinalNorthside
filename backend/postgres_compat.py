"""SQLite-shaped psycopg adapter. Keeps existing AI SQL and flow unchanged."""
import os,re
import psycopg
from psycopg.rows import tuple_row
Error=psycopg.Error
class Row(tuple):
    def __new__(cls, values, keys):
        obj=super().__new__(cls,values);obj.keys_=keys;return obj
    def __getitem__(self,k):
        return super().__getitem__(self.keys_.index(k) if isinstance(k,str) else k)
    def keys(self):return self.keys_
class Cursor:
    def __init__(self,cur):self.cur=cur;self.rowcount=cur.rowcount;self.lastrowid=None
    def fetchone(self):
        row=self.cur.fetchone();return Row(row,[d.name for d in self.cur.description]) if row is not None and self.cur.description else row
    def fetchall(self):return [Row(r,[d.name for d in self.cur.description]) for r in self.cur.fetchall()]
    def __iter__(self):return iter(self.fetchall())
class Connection:
    row_factory=None
    def __init__(self):
        dsn=os.environ.get('DATABASE_URL');
        if not dsn:raise RuntimeError('DATABASE_URL must point to your PostgreSQL database')
        self.conn=psycopg.connect(dsn,autocommit=False)
    def __enter__(self):return self
    def __exit__(self,t,v,tb):
        try:self.conn.rollback() if t else self.conn.commit()
        finally:self.conn.close()
    def execute(self,sql,params=()):
        if 'PRAGMA table_info(appointments)' in sql:
            sql="SELECT ordinal_position-1, column_name FROM information_schema.columns WHERE table_schema='public' AND table_name='appointments' ORDER BY ordinal_position"
        elif sql.strip().upper()=='BEGIN IMMEDIATE':
            sql='SELECT pg_advisory_xact_lock(7214001)'
        sql=re.sub(r'INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT','INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',sql,flags=re.I)
        sql=sql.replace('?', '%s')
        is_insert=bool(re.match(r'\s*INSERT\s+INTO\s+appointments\b',sql,re.I)) and 'RETURNING' not in sql.upper()
        if is_insert:sql+=' RETURNING id'
        cur=self.conn.execute(sql,params)
        wrapped=Cursor(cur)
        if is_insert:
            row=cur.fetchone();wrapped.lastrowid=row[0] if row else None
            if wrapped.lastrowid:
                try:
                    from flask import has_request_context, request, session
                    if has_request_context() and request.path == '/api/chat':
                        self.conn.execute('INSERT INTO booking_sources(appointment_id,source) VALUES (%s,%s) ON CONFLICT DO NOTHING',(wrapped.lastrowid,'AI'))
                        if session.get('site_role')=='patient' and session.get('site_user_id'):
                            self.conn.execute('INSERT INTO appointment_owners(appointment_id,user_id,booking_method) VALUES (%s,%s,%s) ON CONFLICT DO NOTHING',(wrapped.lastrowid,session['site_user_id'],'AI'))
                except ImportError:pass
        return wrapped
    def commit(self):self.conn.commit()
    def rollback(self):self.conn.rollback()
def connect(_unused=None,timeout=15):return Connection()
