@site.post('/appointments')
@protect(role='patient',mutate=True)
def book():
    x=request.get_json(silent=True) or {};service=x.get('service');day=x.get('date');hour=x.get('time')
    if service not in get_services() or not isinstance(day,str) or not isinstance(hour,str):return jsonify(error='Invalid service, date or time.'),400
    try:d=date.fromisoformat(day);t=datetime.strptime(hour,'%H:%M').time()
    except ValueError:return jsonify(error='Invalid date or time.'),400
    from zoneinfo import ZoneInfo
    now=datetime.now(ZoneInfo('Asia/Karachi'))
    if d.weekday()==6 or t.hour<9 or t.hour>=18 or t.minute not in (0,30) or datetime.combine(d,t,tzinfo=ZoneInfo('Asia/Karachi'))<=now:return jsonify(error='Choose a future Monday–Saturday slot between 09:00 and 17:30.'),400
    # Uses same service-specific slot policy as original AI; transaction advisory lock serializes booking operations.
    with pg.connect() as db:
        db.execute('SELECT pg_advisory_xact_lock(7214001)')
        occupied=db.execute("SELECT id FROM appointments WHERE appointment_date=%s AND appointment_time=%s AND service=%s AND status NOT IN ('Cancelled') LIMIT 1",(day,hour,service)).fetchone()
        if occupied:return jsonify(error='That time is already booked for this service.'),409
        row=db.execute('INSERT INTO appointments(customer_name,service,appointment_date,appointment_time,status) VALUES (%s,%s,%s,%s,%s) RETURNING id',(session['site_name'],service,day,hour,'Pending')).fetchone()
        db.execute('INSERT INTO appointment_owners(appointment_id,user_id,booking_method) VALUES (%s,%s,%s)',(row[0],session['site_user_id'],'Manual'))
        db.execute('INSERT INTO booking_sources(appointment_id,source) VALUES (%s,%s)',(row[0],'Manual'))
    return jsonify(id=row[0],message='Appointment request submitted',status='Pending'),201
