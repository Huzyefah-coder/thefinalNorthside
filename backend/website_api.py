@site.post('/services')
@protect(role='staff',mutate=True)
def add_service():
    x=request.get_json(silent=True) or {}
    name=x.get('name','')
    if not isinstance(name,str):return jsonify(error='Enter a valid service name.'),400
    name=' '.join(name.split())
    if not (2<=len(name)<=80) or any(ord(c)<32 for c in name):return jsonify(error='Service name must contain 2–80 characters.'),400
    with pg.connect() as db:
        if db.execute('SELECT id FROM clinic_services WHERE lower(name)=lower(%s)',(name,)).fetchone():return jsonify(error='This service already exists.'),409
        db.execute('INSERT INTO clinic_services(name) VALUES (%s)',(name,))
    return jsonify(message='Service added.',name=name),201

@site.delete('/services/<path:name>')
@protect(role='staff',mutate=True)
def delete_service(name):
    with pg.connect() as db:
        deleted=db.execute('DELETE FROM clinic_services WHERE name=%s RETURNING id',(name,)).fetchone()
    return jsonify(message='Service deleted.') if deleted else (jsonify(error='Service not found.'),404)


