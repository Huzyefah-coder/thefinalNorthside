site=Blueprint('site',__name__,url_prefix='/api/site')
DEFAULT_SERVICES=('General Consultation','Dental Care','Orthopaedics')

def get_services():
    with pg.connect() as db:
        return [r[0] for r in db.execute('SELECT name FROM clinic_services ORDER BY id').fetchall()]


def setup():
    with pg.connect() as db:
        db.execute("""CREATE TABLE IF NOT EXISTS users (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, full_name TEXT NOT NULL,email TEXT NOT NULL UNIQUE,password_hash TEXT NOT NULL,role TEXT NOT NULL DEFAULT 'patient',created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""")
        db.execute("""CREATE TABLE IF NOT EXISTS appointment_owners (appointment_id INTEGER PRIMARY KEY REFERENCES appointments(id) ON DELETE CASCADE,user_id INTEGER NOT NULL REFERENCES users(id),booking_method TEXT NOT NULL DEFAULT 'manual')""")
        db.execute("""CREATE TABLE IF NOT EXISTS booking_sources (appointment_id INTEGER PRIMARY KEY REFERENCES appointments(id) ON DELETE CASCADE, source TEXT NOT NULL)""")
        first_install=not db.execute("SELECT 1 FROM information_schema.tables WHERE table_schema='public' AND table_name='clinic_services'").fetchone()
        db.execute("CREATE TABLE IF NOT EXISTS clinic_services (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL UNIQUE)")
        if first_install:
            # Seed initial options on first install; do not re-add services deliberately deleted later.
            db.execute("INSERT INTO clinic_services(name) VALUES (%s),(%s),(%s)",DEFAULT_SERVICES)
    email=os.getenv('INITIAL_STAFF_EMAIL','').strip().lower();pw=os.getenv('INITIAL_STAFF_PASSWORD','')
    if email and pw:
        with pg.connect() as db:
            if not db.execute('SELECT id FROM users WHERE email=%s',(email,)).fetchone():
                db.execute('INSERT INTO users(full_name,email,password_hash,role) VALUES (%s,%s,%s,%s)',('Clinic Administrator',email,generate_password_hash(pw),'staff'))

def csrf_ok():return request.headers.get('X-CSRF-Token')==session.get('site_csrf') and bool(session.get('site_csrf'))
def protect(role=None,mutate=False):
    def outer(fn):
        @wraps(fn)
        def inner(*a,**kw):
            if not session.get('site_user_id'):return jsonify(error='Please sign in.'),401
            if role and session.get('site_role')!=role:return jsonify(error='Not authorized.'),403
            if mutate and not csrf_ok():return jsonify(error='Invalid CSRF token.'),403
            return fn(*a,**kw)
        return inner
    return outer

