@site.post('/appointments/<int:aid>/reschedule')
@protect(role='patient',mutate=True)
def reschedule(aid):
    x=request.get_json(silent=True) or {};day=x.get('date');hour=x.get('time')
    try:
        from zoneinfo import ZoneInfo
        d=date.fromisoformat(day);t=datetime.strptime(hour,'%H:%M').time();now=datetime.now(ZoneInfo('Asia/Karachi'))
        assert d.weekday()!=6 and 9<=t.hour<18 and t.minute in (0,30) and datetime.combine(d,t,tzinfo=ZoneInfo('Asia/Karachi'))>now
    except (ValueError,TypeError,AssertionError):return jsonify(error='Invalid appointment slot'),400
    with pg.connect() as db:
        db.execute('SELECT pg_advisory_xact_lock(7214001)')
        old=db.execute('SELECT a.service,a.status FROM appointments a JOIN appointment_owners o ON o.appointment_id=a.id WHERE a.id=%s AND o.user_id=%s',(aid,session['site_user_id'])).fetchone()
        if not old or old[1] not in ('Pending','Accepted'):return jsonify(error='Appointment cannot be rescheduled'),409
        if db.execute("SELECT id FROM appointments WHERE service=%s AND appointment_date=%s AND appointment_time=%s AND id<>%s AND status<>'Cancelled'",(old[0],day,hour,aid)).fetchone():return jsonify(error='Slot already booked'),409
        db.execute('UPDATE appointments SET appointment_date=%s,appointment_time=%s,status=%s WHERE id=%s',(day,hour,'Pending',aid))
    return jsonify(message='Appointment rescheduled; pending staff approval')
