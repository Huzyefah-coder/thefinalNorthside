@site.post('/register')
def register():
    x=request.get_json(silent=True) or {};name=str(x.get('name','')).strip();email=str(x.get('email','')).strip().lower();password=str(x.get('password',''))
    if len(name)<2 or not re.fullmatch(r'[^@\s]+@[^@\s]+\.[^@\s]+',email) or len(password)<10:return jsonify(error='Enter a name, valid email and password of at least 10 characters.'),400
    try:
        with pg.connect() as db:
            db.execute('INSERT INTO users(full_name,email,password_hash,role) VALUES (%s,%s,%s,%s)',(name,email,generate_password_hash(password),'patient'))
    except pg.Error:return jsonify(error='Unable to register; email may already be in use.'),409
    return jsonify(message='Account created. Please log in.'),201
